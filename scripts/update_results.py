"""Rebuild RESULTS.md from run outputs (never typed by hand): runs/*/*/metrics.json for nDCG runs, plus the
retrieval / recommendation / pretraining reports. 'vs ZR' is recomputed here from per_query.parquet against the
CURRENT baseline (4-member ZR until Phase 0 stage 3 adds r2, then 5-member), so every row uses the same bar."""
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from mmsearch.esci import ROOT, RUNS  # noqa: E402
from mmsearch.metrics import paired_bootstrap  # noqa: E402
from mmsearch.runlog import baseline_run, load_per_query  # noqa: E402


def ci(d):
    return f"{d['ndcg']:.4f} [{d['ci95'][0]:.4f}, {d['ci95'][1]:.4f}]" if d else "—"


def gain(d):
    return f"{d['gain']:+.4f} [{d['ci95'][0]:+.4f}, {d['ci95'][1]:+.4f}]" if d else "—"


def retrieval_section():
    f = RUNS / "p7" / "report.json"
    if not f.exists():
        return []
    r = json.loads(f.read_text())
    out = ["", "## Phase 7: retrieval (dev queries, 1,215,854 US products)", "",
           "| Retriever | Recall@100 (E) | Recall@1000 (E) | Recall@100 (E+S) | vs BM25 Recall@100 |", "|---|---|---|---|---|"]
    for n, v in r["runs"].items():
        flag = " (optimistic: image pool = judged products)" if v.get("optimistic_image_pool") else ""
        out.append(f"| {n}{flag} | {v['recall@100_E']:.4f} | {v['recall@1000_E']:.4f} | {v['recall@100_ES']:.4f} "
                   f"| {gain(v.get('vs_bm25_recall@100'))} |")
    out.append(f"\nWinner (fair pools only): **{r.get('winner')}**; HNSW (M 32): "
               + ", ".join(f"{k} overlap {v['overlap_with_exact@100']:.3f} at {v['ms_per_query']} ms" for k, v in r.get("hnsw", {}).items()))
    if r.get("e2e"):
        e = r["e2e"]
        out.append(f"\nEnd to end ({e['retriever']} -> {e['rerank_run']}): nDCG@10 {e['ndcg@10_condensed']:.4f} vs "
                   f"{e['ndcg@10_judged_list']:.4f} on the judged list; loss {gain(e['retrieval_loss'])}")
    return out


def main():
    recs = [json.loads(p.read_text()) for p in sorted(RUNS.glob("*/*/metrics.json"))]
    recs.sort(key=lambda r: (r["phase"], not r["run"].startswith("anchor"), r["run"]))
    bl = baseline_run()
    base = load_per_query(*bl)
    splits = pd.read_parquet(RUNS / "p0" / "splits.parquet")["split"]
    dev_q = splits.index[splits == "dev"]
    lines = ["# Results", "",
             "Generated by `scripts/update_results.py` from run outputs; do not edit by hand.",
             "nDCG over each query's judged products (E 1, S 0.1, C 0.01, I 0). Dev = 2,000 queries, final test = 6,956.",
             f"CI = 95% bootstrap over queries; *vs ZR* = paired gain on dev over the current ZR baseline "
             f"(`{'/'.join(bl)}`{'' if base is not None else ', not trained yet'}).", "",
             "| Phase | Run | Dev nDCG [95% CI] | vs ZR baseline | Final test | GPU-h | ms/query |",
             "|---|---|---|---|---|---|---|"]
    for r in recs:
        vs = None
        pq = load_per_query(r["phase"], r["run"])
        if base is not None and pq is not None and (r["phase"], r["run"]) != bl and not r["run"].startswith("anchor"):
            vs = paired_bootstrap(base.reindex(dev_q), pq.reindex(dev_q))
        lines.append(f"| {r['phase']} | {r['run']} | {ci(r['dev'])} | {gain(vs)} | {ci(r.get('test'))} "
                     f"| {r.get('gpu_hours') if r.get('gpu_hours') is not None else '—'} "
                     f"| {r.get('ms_per_query') if r.get('ms_per_query') is not None else '—'} |")
    lines += retrieval_section()
    lines += ["", "## Notes", ""]
    seen = set()
    for r in recs:
        if r.get("notes") and r["notes"] not in seen:
            seen.add(r["notes"])
            lines.append(f"- **{r['run']}**: {r['notes']}")
    (ROOT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print(f"RESULTS.md: {len(recs)} runs")


if __name__ == "__main__":
    main()
